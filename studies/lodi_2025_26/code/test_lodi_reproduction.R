#!/usr/bin/env Rscript
# Independent R verification of Lodi analysis inputs and outputs; run after reproduction.
args <- commandArgs(trailingOnly=TRUE)
root <- if (length(args)) normalizePath(args[[1]]) else dirname(dirname(normalizePath(sub('^--file=', '', grep('^--file=', commandArgs(),value=TRUE)[1]))))
input_dir <- file.path(root, 'inputs')
output_dir <- file.path(root, 'outputs')
read_txt <- function(n, where) read.csv(file.path(where,n), colClasses='character',na.strings=c('','NA'),check.names=FALSE)
meals <- read_txt('lodi_meals_extracted_2025_26.csv', input_dir)
elig <- read_txt('lodi_eligibility_31_schools_source_snapshot.csv', input_dir)
state <- read_txt('lodi_state_proxy_snapshot_2025_26.csv', input_dir)
join <- read_txt('lodi_31_school_k_meal_attendance_review.csv', output_dir)
coverage <- read_txt('lodi_coverage_audit.csv', output_dir)
summary <- read_txt('lodi_k_summary_2025_26.csv', output_dir)
stopifnot(nrow(meals)==31L, nrow(elig)==31L, nrow(state)==35L, nrow(join)==31L, nrow(coverage)==35L)
stopifnot(!anyDuplicated(meals$source_school), !anyDuplicated(join$cds_code))
stopifnot(setequal(join$source_school,elig$school))
stopifnot(setequal(join$source_school,meals$source_school))
stopifnot(setequal(join$cds_code,state$cds_code[state$school_name %in% join$cde_school]))
stopifnot(sum(coverage$meal_workbook=='yes')==31L, sum(coverage$meal_workbook=='no')==4L)
stopifnot(!anyNA(join$estimated_k_attended_days), all(as.numeric(join$estimated_k_attended_days)>0))
num <- function(x) suppressWarnings(as.numeric(x))
stopifnot(sum(num(join$k_breakfast_meals)) == 70667)
stopifnot(sum(num(join$k_lunch_meals)) == 203639)
stopifnot(sum(num(join$k_census)) == 1763)
stopifnot(sum(num(join$tk_census)) == 853)
stopifnot(abs(sum(num(join$estimated_k_attended_days))-287174.3372854)<1e-3)
stopifnot(abs(num(summary$breakfasts_per_100_attended_days)-24.607700210262735)<1e-7)
stopifnot(abs(num(summary$lunches_per_100_attended_days)-70.91128055694587)<1e-7)

cat('PASS: 31 school joins, 35 source schools, meals, K denominator and ratios verified.\n')